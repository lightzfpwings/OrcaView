"""M3 static input and dependency checks without Qt or an ORCA executable."""

from dataclasses import FrozenInstanceError, replace
from hashlib import sha256
from pathlib import Path
import tempfile
import unittest

from orcaview.application.document import MoleculeDocument
from orcaview.core.models import Atom, Bond, CalculationSpec, Molecule
from orcaview.core.provenance import Provenance
from orcaview.editing import EditorService, GeometryEditCommand, ReorderAtoms, SetElectronicState
from orcaview.orca.input import InputCompanionFile, InputSnapshot, freeze_input, render_input


WATER_XYZ = b"3\nwater fixture\nO 0 0 0\nH 1 0 0\nH -0.25 1 0\n"
SYNTHETIC_GBW = b"\x00synthetic GBW bytes\xff"


class InputSnapshotTests(unittest.TestCase):
    def setUp(self):
        self.molecule = Molecule(
            "water", (Atom("O", 0, 0, 0), Atom("H", 1, 0, 0), Atom("H", -0.25, 1, 0)),
            (Bond(0, 1), Bond(0, 2)),
        )
        self.document = MoleculeDocument.from_molecule(self.molecule, source_unit="bohr")
        self.geometry = self.document.head
        self.spec = CalculationSpec()

    def test_builtin_templates_and_frozen_bytes_match_eight_decimal_output(self):
        for job_type, keywords in (("SP", b"SP"), ("OPT", b"Opt"),
                                   ("FREQ", b"Freq"), ("OPT_FREQ", b"Opt Freq")):
            with self.subTest(job_type=job_type):
                spec = replace(self.spec, job_type=job_type)
                expected = (
                    b"# Generated by OrcaView prototype; review before running ORCA.\n"
                    b"! B3LYP def2-SVP " + keywords + b"\n"
                    b"%pal\n  nprocs 16\nend\n%maxcore 4096\n* xyz 0 1\n"
                    b"  O   0.00000000  0.00000000  0.00000000\n"
                    b"  H   1.00000000  0.00000000  0.00000000\n"
                    b"  H  -0.25000000  1.00000000  0.00000000\n*\n"
                )
                frozen = freeze_input(self.geometry, spec)
                self.assertIsInstance(frozen, InputSnapshot)
                self.assertEqual(frozen.contract_version, 1)
                self.assertEqual(frozen.target_orca_version, "6.1.1")
                self.assertEqual(freeze_input(self.geometry, spec, target_orca_version="6.1").input_bytes, expected)
                self.assertEqual(frozen.main_input_path, "job.inp")
                self.assertEqual(frozen.encoding, "utf-8")
                self.assertEqual(frozen.input_bytes, expected)
                self.assertEqual(frozen.input_text, render_input(self.molecule, spec))
                self.assertEqual(frozen.input_text.encode(frozen.encoding), expected)
                self.assertEqual(frozen.input_sha256, sha256(expected).hexdigest())
                self.assertEqual(frozen.estimated_maxcore_mb, 65536)
                self.assertEqual(frozen.companions, ())

    def test_content_digest_repeats_and_excludes_geometry_identity(self):
        frozen = freeze_input(self.geometry, self.spec)
        repeated = freeze_input(self.geometry, replace(self.spec))
        independent = MoleculeDocument.from_molecule(self.molecule)
        foreign = freeze_input(independent.head, self.spec)
        self.assertEqual(repeated.content_digest, frozen.content_digest)
        self.assertEqual(repeated.snapshot_digest, frozen.snapshot_digest)
        self.assertEqual(foreign.content_digest, frozen.content_digest)
        self.assertNotEqual(foreign.snapshot_digest, frozen.snapshot_digest)
        self.assertEqual(len(frozen.content_digest), 64)
        self.assertEqual(len(frozen.snapshot_digest), 64)

    def test_actual_frames_and_same_number_branch_revisions_keep_full_reference(self):
        branch = MoleculeDocument.restore(*self.document.records())
        left = self.document.publish_revision(self.geometry.ref, self.molecule, self.geometry.atom_ids)
        right = branch.publish_revision(self.geometry.ref, self.molecule, self.geometry.atom_ids)
        left_frame = self.document.add_frame(left.ref, "final", self.molecule, left.atom_ids,
                                             Provenance("synthetic-fixture"))
        right_frame = branch.add_frame(right.ref, "final", self.molecule, right.atom_ids,
                                       Provenance("synthetic-fixture"))
        snapshots = tuple(freeze_input(geometry, self.spec)
                          for geometry in (left, right, left_frame, right_frame))
        self.assertEqual(len({snapshot.content_digest for snapshot in snapshots}), 1)
        self.assertEqual(len({snapshot.snapshot_digest for snapshot in snapshots}), 4)
        self.assertEqual(tuple(snapshot.geometry_ref for snapshot in snapshots),
                         (left.ref, right.ref, left_frame.ref, right_frame.ref))
        self.assertEqual(snapshots[-1].geometry_ref.frame_id, "final")
        self.assertEqual(snapshots[-1].geometry_ref.revision, 2)
        self.assertEqual(snapshots[-1].geometry_ref.document_id, self.geometry.ref.document_id)

    def test_m2_order_geometry_electronic_state_and_settings_changes_leave_snapshot_frozen(self):
        before = freeze_input(self.geometry, self.spec)
        o, h1, h2 = self.geometry.atom_ids
        editor = EditorService(self.document)
        editor.commit(editor.preview(GeometryEditCommand(editor.expected, ReorderAtoms((h2, o, h1)))))
        editor.commit(editor.preview(GeometryEditCommand(editor.expected, SetElectronicState(1, 2))))
        moved = self.document.head.molecule
        moved = replace(moved, atoms=(replace(moved.atoms[0], y=1.25), *moved.atoms[1:]))
        head = self.document.publish_revision(editor.expected, moved, self.document.head.atom_ids)
        new_spec = replace(self.spec, method="HF", basis="def2-TZVP", job_type="OPT", cores=2,
                           maxcore_mb=1500)
        after = freeze_input(head, new_spec)
        self.assertEqual(before.geometry_ref, self.geometry.ref)
        self.assertEqual(before.geometry.molecule, self.molecule)
        self.assertEqual(before.geometry.source_unit, "bohr")
        self.assertEqual(before.spec, self.spec)
        self.assertEqual(before.atom_indices, {o: 0, h1: 1, h2: 2})
        self.assertEqual(after.atom_indices, {h2: 0, o: 1, h1: 2})
        self.assertIn(b"* xyz 0 1\n", before.input_bytes)
        self.assertIn(b"* xyz 1 2\n", after.input_bytes)
        self.assertIn(b"1.25000000", after.input_bytes)
        self.assertIn(b"! HF def2-TZVP Opt\n", after.input_bytes)
        self.assertEqual(after.estimated_maxcore_mb, 3000)
        self.assertNotEqual(before.content_digest, after.content_digest)
        self.assertEqual(before.snapshot_digest,
                         freeze_input(self.document.resolve(before.geometry_ref), self.spec).snapshot_digest)
        with self.assertRaises(TypeError):
            before.atom_indices[o] = 8
        with self.assertRaises(FrozenInstanceError):
            before.input_bytes = b"replacement"

    def test_electronic_state_and_settings_affect_digest_without_new_geometry_hash(self):
        before = freeze_input(self.geometry, self.spec)
        for charge, multiplicity in ((1, 2), (0, 3)):
            with self.subTest(charge=charge, multiplicity=multiplicity):
                changed = replace(self.molecule, charge=charge, multiplicity=multiplicity)
                head = self.document.head
                geometry = self.document.publish_revision(head.ref, changed, head.atom_ids)
                self.assertEqual(geometry.content_hash, self.geometry.content_hash)
                self.assertNotEqual(freeze_input(geometry, self.spec).content_digest, before.content_digest)
        for settings in ({"method": "HF"}, {"basis": "def2-TZVP"}, {"job_type": "FREQ"},
                         {"cores": 2}, {"maxcore_mb": 1500}):
            with self.subTest(settings=settings):
                frozen = freeze_input(self.geometry, replace(self.spec, **settings))
                self.assertNotEqual(frozen.content_digest, before.content_digest)

    def test_structured_settings_and_target_remain_whitelisted(self):
        for settings in ({"method": "B3LYP\n%pal"}, {"basis": "def2-SVP #comment"},
                         {"method": "Mulliken"}, {"basis": "invalid-basis"}, {"job_type": "SP\n%pal"},
                         {"job_type": "TS"}, {"cores": True}, {"maxcore_mb": 0}):
            with self.subTest(settings=settings), self.assertRaises(ValueError):
                freeze_input(self.geometry, replace(self.spec, **settings))
        for version in ("5.0", "6.2", "6.1\n%pal", None):
            with self.subTest(version=version), self.assertRaises(ValueError):
                freeze_input(self.geometry, self.spec, target_orca_version=version)
        invalid = replace(self.geometry, molecule=replace(self.molecule, multiplicity=2))
        with self.assertRaises(ValueError):
            freeze_input(invalid, self.spec)

    def test_declared_companions_retain_exact_bytes_after_sources_change_or_disappear(self):
        with tempfile.TemporaryDirectory() as directory:
            xyz_source = Path(directory) / "source.xyz"
            gbw_source = Path(directory) / "source.gbw"
            xyz_source.write_bytes(WATER_XYZ)
            gbw_source.write_bytes(SYNTHETIC_GBW)
            xyz = InputCompanionFile.from_path("external_xyz", "water.xyz", xyz_source)
            gbw = InputCompanionFile.from_path("initial_gbw", "guess.gbw", gbw_source)
            frozen = freeze_input(self.geometry, self.spec, companions=(xyz, gbw))
            xyz_source.write_bytes(b"changed xyz")
            gbw_source.unlink()
            repeated = freeze_input(self.geometry, self.spec, companions=(gbw, xyz))
            self.assertEqual(frozen.snapshot_digest, repeated.snapshot_digest)
            self.assertEqual(frozen.input_sha256, sha256(frozen.input_bytes).hexdigest())
            self.assertEqual(frozen.companions, (gbw, xyz))
            self.assertEqual(gbw.content, SYNTHETIC_GBW)
            self.assertEqual(gbw.sha256, sha256(SYNTHETIC_GBW).hexdigest())
            self.assertEqual(xyz.content, WATER_XYZ)
            self.assertEqual(xyz.sha256, sha256(WATER_XYZ).hexdigest())
            self.assertTrue(frozen.input_bytes.endswith(b"* xyzfile 0 1 water.xyz\n\n"))
            self.assertIn(b'%moinp "guess.gbw"\n', frozen.input_bytes)
            self.assertIn(b"moread", frozen.input_bytes.lower())
            self.assertNotIn(b"source.", frozen.input_bytes)
            with self.assertRaises(ValueError):
                InputCompanionFile.from_path("initial_gbw", "guess.gbw", gbw_source)

    def test_manifest_paths_and_companion_payloads_are_part_of_content_digest(self):
        gbw = InputCompanionFile("initial_gbw", "guess.gbw", SYNTHETIC_GBW)
        original = freeze_input(self.geometry, self.spec, companions=(gbw,))
        for changed in (replace(gbw, relative_path="different.gbw"),
                        replace(gbw, content=b"different payload")):
            with self.subTest(changed=changed.relative_path):
                frozen = freeze_input(self.geometry, self.spec, companions=(changed,))
                self.assertNotEqual(frozen.content_digest, original.content_digest)
        moved_main = freeze_input(self.geometry, self.spec, main_input_path="sample.inp", companions=(gbw,))
        self.assertEqual(moved_main.input_sha256, original.input_sha256)
        self.assertNotEqual(moved_main.content_digest, original.content_digest)

    def test_unknown_duplicate_unsafe_and_nonimmutable_companions_are_rejected(self):
        for role, path, data in (
            ("other", "geometry.xyz", WATER_XYZ),
            ("external_xyz", "../water.xyz", WATER_XYZ),
            ("external_xyz", "/water.xyz", WATER_XYZ),
            ("external_xyz", "jobfiles/water.xyz", WATER_XYZ),
            ("external_xyz", r"jobfiles\water.xyz", WATER_XYZ),
            ("external_xyz", "water.xyz\n%pal", WATER_XYZ),
            ("external_xyz", "COM1.xyz", WATER_XYZ),
            ("external_xyz", "water.txt", WATER_XYZ),
            ("initial_gbw", "guess.gbw", b""),
            ("initial_gbw", "guess.gbw", bytearray(SYNTHETIC_GBW)),
        ):
            with self.subTest(role=role, path=path, data_type=type(data)), self.assertRaises(ValueError):
                InputCompanionFile(role, path, data)
        for path in ("JOB.gbw", "job_guess.gbw"):
            with self.subTest(path=path), self.assertRaises(ValueError):
                guess = InputCompanionFile("initial_gbw", path, SYNTHETIC_GBW)
                freeze_input(self.geometry, self.spec, companions=(guess,))
        for path in ("JOB.xyz", "job_trj.xyz"):
            with self.subTest(path=path), self.assertRaises(ValueError):
                xyz = InputCompanionFile("external_xyz", path, WATER_XYZ)
                freeze_input(self.geometry, replace(self.spec, job_type="OPT"), companions=(xyz,))
        first = InputCompanionFile("initial_gbw", "Guess.gbw", SYNTHETIC_GBW)
        for name in ("guess.gbw", "other.gbw"):
            with self.subTest(name=name), self.assertRaises(ValueError):
                second = InputCompanionFile("initial_gbw", name, SYNTHETIC_GBW)
                freeze_input(self.geometry, self.spec, companions=(first, second))
        for companions in ((object(),), [first]):
            with self.subTest(companions=companions), self.assertRaises(ValueError):
                freeze_input(self.geometry, self.spec, companions=companions)
        for main in ("../job.inp", "folder/job.inp", "job.inp\n", "job.xyz"):
            with self.subTest(main=main), self.assertRaises(ValueError):
                freeze_input(self.geometry, self.spec, main_input_path=main)

    def test_external_xyz_must_agree_with_frozen_atom_rows_and_angstrom_units(self):
        for data in (
            WATER_XYZ.replace(b"H 1 0 0", b"H 2 0 0"),
            WATER_XYZ.replace(b"O 0 0 0\nH 1 0 0", b"H 1 0 0\nO 0 0 0"),
            WATER_XYZ.replace(b"water fixture", b"units=bohr"),
            WATER_XYZ + WATER_XYZ,
            WATER_XYZ.replace(b"O 0 0 0", b"O 0 0 0 extra"),
            WATER_XYZ.replace(b"H 1 0 0", b"H NaN 0 0"),
            WATER_XYZ.replace(b"H 1 0 0", b"H 0_1 0 0"),
            WATER_XYZ.replace(b"water fixture", b"water\x00fixture"),
            WATER_XYZ.rstrip(b"\n"),
        ):
            with self.subTest(data=data), self.assertRaises(ValueError):
                xyz = InputCompanionFile("external_xyz", "water.xyz", data)
                freeze_input(self.geometry, self.spec, companions=(xyz,))
        # A supplied XYZ may carry more precision than the inline ORCA representation.
        raw = WATER_XYZ.replace(b"H 1 0 0", b"H +1.000000000031e0 0 -0.0").replace(b"\n", b"\r\n")
        xyz = InputCompanionFile("external_xyz", "water.xyz", raw)
        with self.assertRaises(ValueError):
            freeze_input(self.geometry, self.spec, companions=(xyz,))
        oxygen, first_h, second_h = self.molecule.atoms
        atoms = oxygen, replace(first_h, x=1.000000000031), second_h
        head = MoleculeDocument.from_molecule(replace(self.molecule, atoms=atoms)).head
        frozen = freeze_input(head, self.spec, companions=(xyz,))
        self.assertTrue(frozen.input_text.endswith("* xyzfile 0 1 water.xyz\n\n"))
        self.assertEqual(frozen.companions[0].content, raw)
        self.assertEqual(frozen.companions[0].sha256, sha256(raw).hexdigest())


if __name__ == "__main__":
    unittest.main()
