_XYZ_COUNT = re.compile(r"[ \t]*[0-9]+[ \t]*")
_XYZ_TEXT = re.compile(r"(?:[\t\x20-\x7e]|\r?\n)+")
_XYZ_NUMBER = re.compile(r"[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[Ee][+-]?[0-9]+)?")
GENERATED_COMMENT = "Generated by OrcaView prototype; review before running ORCA."


def inline_coordinate(value):
    return format(value, " .8f")


def method_input(spec, multiplicity):
    if spec.method in ACTIVE_SPACE_METHODS or spec.method in EXCITED_STATE_METHODS:
        return state_keywords_and_block(spec.method, spec.active_electrons, spec.active_orbitals, spec.nroots,
                                        spec.reference_functional, multiplicity, spec.electron_channel)
    words, block = advanced_input(spec.method, multiplicity)
    return DISPERSION_RECIPES.get(spec.method, words), block


def render_input(molecule: Molecule, spec: CalculationSpec) -> str:
    """Render the existing inline preview used by the CLI and desktop session."""
    return _render_input(molecule, spec)


def _render_input(
    molecule: Molecule,
    spec: CalculationSpec,
    external_xyz: Optional[str] = None,
    initial_gbw: Optional[str] = None,
) -> str:
    molecule.validate()
    spec.validate()
    preset = METHODS[spec.method]
    preset.validate_system(molecule)
    if spec.wavefunction in ("RHF", "RKS") and molecule.multiplicity != 1:
        raise ValueError("A restricted closed-shell reference requires a singlet")
    if spec.wavefunction in ("ROHF", "ROKS") and molecule.multiplicity == 1:
        raise ValueError("This restricted open-shell template requires a high-spin state with multiplicity greater than one")
    if spec.method in ACTIVE_SPACE_METHODS or spec.method in EXCITED_STATE_METHODS:
        validate_state_system(spec.method, molecule, spec.active_electrons, spec.active_orbitals,
                              electron_channel=spec.electron_channel, basis=spec.basis)
    method_keywords, method_block = method_input(spec, molecule.multiplicity)
    options, basis_block = orbital_and_aux_input(spec, molecule)
    options += tuple(value for value in (spec.wavefunction, spec.dispersion, spec.pno_preset) if value != "Auto")
    if spec.frozen_core == "NoFrozenCore":
        options += ("NoFrozenCore",)
    if spec.scf_convergence != "Auto":
        options += (spec.scf_convergence,)
    overrides = validated_block_values(spec)
    for control, spellings in SIMPLE_INPUT_CONTROLS.items():
        key = control.block, control.key
        value = overrides.get(key)
        if value in spellings:
            options += (spellings[value],)
            del overrides[key]
    solvent_words, solvent_block = solvation_input(spec)
    keywords = "! " + preset.keywords(options + solvent_words, spec.job_type, method_keywords,
                                      numerical_frequency=uses_numerical_frequencies(spec))
    if initial_gbw is not None:
        if not preset.allows_initial_gbw:
            raise ValueError(f"The {spec.method} template does not support an external GBW initial guess")
        keywords += " MORead"
    if overrides.get(("irc", "hessMode"), 0) >= 3 * len(molecule.atoms):
        raise ValueError("The initial IRC Hessian mode index exceeds the Cartesian degrees of freedom")
    template_blocks = (
        *basis_block,
        *(("%method", "  FrozenCore FC_ELECTRONS", "end") if spec.frozen_core == "FrozenCore" else ()),
        *method_block,
        *solvent_block,
    )
    lines = [
        "# " + GENERATED_COMMENT,
        *("# " + note for note in spec.input_comments),
        keywords,
        "%pal", f"  nprocs {spec.cores}", "end",
        f"%maxcore {spec.maxcore_mb}",
        *merge_block_lines(template_blocks, reaction_path.generated_options(spec, overrides)),
    ]
    if initial_gbw is not None:
        lines.append(f'%moinp "{initial_gbw}"')
    electronic_state = f"{molecule.charge} {molecule.multiplicity}"
    if external_xyz is None:
        lines.append(f"* xyz {electronic_state}")
        lines.extend(f"  {a.element:<2} {inline_coordinate(a.x)} {inline_coordinate(a.y)} {inline_coordinate(a.z)}"
                     for a in molecule.atoms)
        lines.append("*")
    else:
        lines.extend([f"* xyzfile {electronic_state} {external_xyz}", ""])
    return "\n".join(lines) + "\n"


def _validate_external_xyz(file: InputCompanionFile, molecule: Molecule) -> None:
    # Validate raw tokens before the normal parser, whose Python numeric and
    # whitespace syntax accepts additional spellings beyond the ORCA profile.
    try:
        text = file.content.decode("ascii")
    except UnicodeDecodeError as exc:
        raise ValueError("External XYZ files must use ASCII text") from exc
    if not text.endswith("\n") or not _XYZ_TEXT.fullmatch(text):
        raise ValueError("External XYZ files must use plain text lines and a final newline")
    lines = text.splitlines()
    if not _XYZ_COUNT.fullmatch(lines[0]):
        raise ValueError("The first line of an external XYZ file must be a decimal atom count")
    record = parse_xyz_record(text)
    if record.source_unit != "angstrom":
        raise ValueError("External XYZ coordinates must be in angstroms")
    for line in lines[2:2 + len(record.molecule.atoms)]:
        if any(not _XYZ_NUMBER.fullmatch(token) for token in line.split()[1:]):
            raise ValueError("External XYZ coordinates must use decimal numbers or E notation")
    if record.molecule.atoms != molecule.atoms:
        raise ValueError("External XYZ elements, atom order or coordinates differ from the frozen geometry")


def _digest(domain: str, payload: dict) -> str:
    canonical = json.dumps(payload, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    return sha256(domain.encode("ascii") + b"\0" + canonical.encode("ascii")).hexdigest()


@dataclass(frozen=True)
class InputSnapshot(Versioned):
    """Exact ORCA input and declared resources bound to one source geometry."""

    geometry: GeometrySnapshot
    spec: CalculationSpec
    target_orca_version: str = ORCA_INPUT_TARGET
    main_input_path: str = "job.inp"
    companions: Tuple[InputCompanionFile, ...] = ()
    encoding: ClassVar[str] = "utf-8"
    input_bytes: bytes = field(init=False, repr=False)
    input_sha256: str = field(init=False)
    atom_indices: Mapping[str, int] = field(init=False, repr=False, compare=False)
    content_digest: str = field(init=False)
    snapshot_digest: str = field(init=False)

    def __post_init__(self) -> None:
        if self.target_orca_version not in (ORCA_INPUT_TARGET, "6.1"):
            raise ValueError("Input snapshots support ORCA 6.1 or the exact version 6.1.1")
        if not isinstance(self.geometry, GeometrySnapshot) or not isinstance(self.spec, CalculationSpec):
            raise ValueError("An input snapshot requires a GeometrySnapshot and a CalculationSpec")

        companions = validate_companion_manifest(self.main_input_path, self.companions)
        by_role = {file.role: file for file in companions}
        xyz = by_role.get("external_xyz")
        gbw = by_role.get("initial_gbw")
        if xyz is not None:
            _validate_external_xyz(xyz, self.geometry.molecule)
        input_bytes = _render_input(
            self.geometry.molecule,
            self.spec,
            external_xyz=None if xyz is None else xyz.relative_path,
            initial_gbw=None if gbw is None else gbw.relative_path,
        ).encode(self.encoding)
        input_sha256 = sha256(input_bytes).hexdigest()
        content_digest = _digest("orcaview/orca-input-content/1", {
            "target_orca_version": self.target_orca_version,
            "encoding": self.encoding,
            "main_input": {"relative_path": self.main_input_path, "sha256": input_sha256},
            "companions": [{"role": file.role, "relative_path": file.relative_path, "sha256": file.sha256}
                           for file in companions],
        })
        ref = self.geometry.ref
        atom_indices = {atom_id: index for index, atom_id in enumerate(self.geometry.atom_ids)}
        snapshot_digest = _digest("orcaview/orca-input-snapshot/1", {
            "content_digest": content_digest,
            "geometry_ref": {"contract_version": ref.contract_version, "document_id": ref.document_id,
                             "revision": ref.revision, "frame_id": ref.frame_id,
                             "snapshot_id": ref.snapshot_id},
            "geometry_content_hash": self.geometry.content_hash,
            "atom_ids": self.geometry.atom_ids,
        })
        object.__setattr__(self, "companions", companions)
        object.__setattr__(self, "input_bytes", input_bytes)
        object.__setattr__(self, "input_sha256", input_sha256)
        object.__setattr__(self, "atom_indices", MappingProxyType(atom_indices))
        object.__setattr__(self, "content_digest", content_digest)
        object.__setattr__(self, "snapshot_digest", snapshot_digest)

    @property
    def geometry_ref(self) -> GeometryRef:
        return self.geometry.ref

    @property
    def input_text(self) -> str:
        return self.input_bytes.decode(self.encoding)

    @property
    def estimated_maxcore_mb(self) -> int:
        """The largest configured module MaxCore multiplied by nprocs, in MB."""
        return self.spec.cores * self.spec.peak_maxcore_per_process


def freeze_input(
    geometry: GeometrySnapshot,
    spec: CalculationSpec,
    *,
    target_orca_version: str = ORCA_INPUT_TARGET,
    main_input_path: str = "job.inp",
    companions: Tuple[InputCompanionFile, ...] = (),
) -> InputSnapshot:
    """Validate and freeze one ORCA job without consulting the live document."""
    return InputSnapshot(geometry, spec, target_orca_version, main_input_path, companions)
