"""Compare ORCA 6.1.1 solvent tables column by column, then emit the input data.

Usage: python tools/audit_orca_solvents.py HTML_ROOT PDF_LAYOUT_TEXT
Requires lxml for this maintenance operation. Produce PDF_LAYOUT_TEXT with pdftotext -layout.
"""

import argparse
import re
from pathlib import Path

from lxml import html


def table_rows(html_file, caption):
    page = html.parse(str(html_file))
    table = next(c.getparent() for c in page.xpath("//article//caption")
                 if caption in c.text_content())
    for row in table.xpath("./tbody/tr"):
        yield tuple(" ".join(cell.text_content().split()) for cell in row)


def pdf_rows(pages, headings):
    rows = []
    for page in pages:
        columns = ()
        for line in page.splitlines():
            if line.lstrip().startswith("Solvent ") and all(label in line for label in headings):
                columns = tuple(line.index(label) for label in headings)
                continue
            if not columns:
                continue
            cells = re.fullmatch(r"\s*(.+?)\s{2,}(X\s*(?:X\s*)*)", line)
            if cells:
                marks = [m.start() + cells.start(2) for m in re.finditer("X", cells[2])]
                flags = tuple("X" if any(abs(pos - column) <= 1 for pos in marks) else ""
                              for column in columns)
                if flags.count("X") != len(marks):
                    raise ValueError(f"Unaligned flags in PDF: {line}")
                rows.append((cells[1], *flags))
    return rows


def model_library(web, layout):
    pages = layout.read_text().split("\f")
    definitions = (
        ("essentialelements/solvationmodels.html", "Table 2.56", 143, 147,
         ("C-PCM", "SMD", "COSMO-RS", "ALPB"), ("CPCM", "SMD", None, "ALPB")),
        ("modelchemistries/semiempirical.html", "Table 3.24", 263, 264,
         ("ALPB", "ddCOSMO", "CPCM-X"), ("ALPB", "DDCOSMO", "CPCMX")),
    )
    library = {}
    alpb_names = None
    for source, caption, start, end, headings, models in definitions:
        online = list(table_rows(web / "contents" / source, caption))
        printed = pdf_rows(pages[start-1:end], headings)
        if online != printed:
            mismatch = next(((a, b) for a, b in zip(online, printed) if a != b), None)
            raise ValueError(f"{caption}: HTML {len(online)} rows / PDF {len(printed)} rows: {mismatch}")
        pending = ""
        edition_alpb = set()
        for names, *flags in online:
            # A line break in both versions splits the sulfolane aliases over two marked rows.
            if names.endswith("/"):
                pending = names
                continue
            names = pending + names.lstrip("/") if pending else names
            pending = ""
            aliases = [s.strip() for s in names.split("/") if s.strip()]
            allowed = {m for m, flag in zip(models, flags) if m and flag == "X"}
            if "ALPB" in allowed:
                edition_alpb.update(aliases)
            for alias in aliases:
                library.setdefault(alias, set()).update(allowed)
        if pending:
            raise ValueError(f"Unfinished solvent row: {pending}")
        if alpb_names is not None and alpb_names != edition_alpb:
            raise ValueError("ALPB aliases differ between the solvation and xTB chapters")
        alpb_names = edition_alpb
    return library


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("html", type=Path)
    p.add_argument("layout", type=Path)
    args = p.parse_args()
    solvents = model_library(args.html, args.layout)
    print('"""Named solvent aliases validated against ORCA 6.1.1 tables 2.56 and 3.24.')
    print('Generated by tools/audit_orca_solvents.py. Each line lists the applicable models.')
    print('"""\n\nSOLVENT_ROWS = """')
    for key, values in sorted(solvents.items()):
        if values:
            print(key + "|" + " ".join(sorted(values)))
    print('""".strip().splitlines()')
